package report

import (
	"fmt"
	"strings"

	"github.com/ayanasarkar/vapt-agent/internal/audit"
	"github.com/ayanasarkar/vapt-agent/internal/model"
)

func headHash(es []audit.Entry) string {
	if len(es) == 0 {
		return "-"
	}
	return es[len(es)-1].Hash
}

func clip(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	if len([]rune(s)) <= n {
		return s
	}
	return string([]rune(s)[:n-1]) + "…"
}
func orNone(s []string) string {
	if len(s) == 0 {
		return "none"
	}
	return strings.Join(s, ", ")
}
func orAny(p []int) string {
	if len(p) == 0 {
		return "any"
	}
	return fmt.Sprint(p)
}
func orAnyS(s []string) string {
	if len(s) == 0 {
		return "all registered tools"
	}
	return strings.Join(s, ", ")
}
func orDash(s []string) string {
	if len(s) == 0 {
		return "-"
	}
	return strings.Join(s, ", ")
}
func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
func orText(s, alt string) string {
	if strings.TrimSpace(s) == "" {
		return alt
	}
	return s
}
func yesNo(b bool, y, n string) string {
	if b {
		return y
	}
	return n
}
func label(by string) string {
	if by == "" || by == "rules" {
		return "generated by the deterministic rules engine"
	}
	return "generated by " + by + ", checked against tool evidence"
}
func modeShort(m string) string {
	switch {
	case strings.HasPrefix(m, "import"):
		return "import"
	case strings.Contains(m, "gated"):
		return "gated"
	case m == "":
		return "-"
	}
	return "live"
}
func shortBy(b string) string {
	if strings.HasPrefix(b, "llm:") {
		return "LLM"
	}
	return b
}
func assetList(f model.Finding) string {
	var a []string
	for _, x := range f.Assets {
		a = append(a, fmt.Sprintf("%s:%d", x.Host, x.Port))
	}
	return strings.Join(a, ", ")
}
func firstS(s []string, n int) []string {
	if len(s) > n {
		return s[:n]
	}
	return s
}
