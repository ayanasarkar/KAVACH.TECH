func headHash(es []audit.Entry) string {
	if len(es) == 0 {
		return "-"
	}
	return es[len(es)-1].Hash
}

func clip(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	if len([]rune(s)) <= n {
		return s
	}
	return string([]rune(s)[:n-1]) + "…"
}
func orNone(s []string) string {
	if len(s) == 0 {
		return "none"
	}
	return strings.Join(s, ", ")
}
func orAny(p []int) string {
	if len(p) == 0 {
		return "any"
	}
	return fmt.Sprint(p)
}
func orAnyS(s []string) string {
	if len(s) == 0 {
		return "all registered tools"
	}
	return strings.Join(s, ", ")
}
func orDash(s []string) string {
	if len(s) == 0 {
		return "-"
	}
	return strings.Join(s, ", ")
}
func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
func orText(s, alt string) string {
	if strings.TrimSpace(s) == "" {
		return alt
	}
	return s
}
func yesNo(b bool, y, n string) string {
	if b {
		return y
	}
	return n
}
func label(by string) string {
	if by == "" || by == "rules" {
		return "generated by the deterministic rules engine"
	}
	return "generated by " + by + ", checked against tool evidence"
}
func modeShort(m string) string {
	switch {
	case strings.HasPrefix(m, "import"):
		return "import"
	case strings.Contains(m, "gated"):
		return "gated"
	case m == "":
		return "-"
	}
	return "live"
}
func shortBy(b string) string {
	if strings.HasPrefix(b, "llm:") {
		return "LLM"
	}
	return b
}

// assetSummary lists a finding's assets compactly, grouped by host: "www.example.com (:80, :443, :8000)".
// Every asset sharing a host prints that host once, so the ports are never what a table cell cuts off.
func assetSummary(f model.Finding) string {
	var order []string
	ports := map[string][]string{}
	for _, x := range f.Assets {
		if _, seen := ports[x.Host]; !seen {
			order = append(order, x.Host)
			ports[x.Host] = nil
		}
		if x.Port > 0 {
			ports[x.Host] = append(ports[x.Host], fmt.Sprintf(":%d", x.Port))
		}
	}
	var parts []string
	for _, h := range order {
		if len(ports[h]) == 0 {
			parts = append(parts, h)
			continue
		}
		parts = append(parts, fmt.Sprintf("%s (%s)", h, strings.Join(ports[h], ", ")))
	}
	return strings.Join(parts, "; ")
}

// assetCell is assetSummary laid out for a narrow table cell: each host on its own line with its port list
// beneath it, so a wrapped cell never splits the ports of one host across lines.
func assetCell(f model.Finding) string {
	return strings.ReplaceAll(strings.ReplaceAll(assetSummary(f), "; ", "\n"), " (", "\n(")
}

// outcomeText shortens a step summary for the Outcome column. Webcheck summaries start with the URL they hit
// ("http://h:8000 -> HTTP 200, 4 issues"), which the Target column beside it already shows, so that repeat is
// dropped. A summary whose URL differs from the target (a protocol fallback corrected the scheme) is kept whole,
// because the corrected URL is exactly what a reader needs to see.
func outcomeText(summary, target string) string {
	if i := strings.Index(summary, " -> "); i > 0 && strings.TrimSpace(summary[:i]) == strings.TrimSpace(target) {
		return summary[i+len(" -> "):]
	}
	return summary
}

func firstS(s []string, n int) []string {
	if len(s) > n {
		return s[:n]
	}
	return s
}

// addressingLine states which addressing rule the scope guard actually enforced for this run. Three cases:
// organiser override (any address), explicitly authorised public domains (public unicast only, private/loopback/
// link-local refused at plan time and again at connect time), or the default lab-only rule.
func addressingLine(allowNonLab bool, authorizedDomains []string) string {
	switch {
	case allowNonLab:
		return "Addressing rule: organiser override recorded (non-lab addresses permitted for in-scope targets)"
	case len(authorizedDomains) > 0:
		return "Addressing rule: lab-only (loopback/private ranges) for IP targets; explicitly authorised domain(s) " +
			strings.Join(authorizedDomains, ", ") +
			" permitted only while they resolve to public addresses (private, loopback and link-local results refused at plan time and at connect time)"
	default:
		return "Addressing rule: lab-only enforced (loopback/private ranges only)"
	}
}
